-- Warstwa RAW: stage + tabele z kolumną VARIANT.
CREATE SCHEMA IF NOT EXISTS SEJM.RAW;
CREATE SCHEMA IF NOT EXISTS SEJM.STAGING;
CREATE SCHEMA IF NOT EXISTS SEJM.MARTS;

-- Pliki z ingestu to tablice JSON – STRIP_OUTER_ARRAY robi z każdego
-- elementu osobny wiersz (odpowiednik read_json_objects(format='array')).
CREATE FILE FORMAT IF NOT EXISTS SEJM.RAW.JSON_ARRAY
  TYPE = JSON
  STRIP_OUTER_ARRAY = TRUE;

CREATE STAGE IF NOT EXISTS SEJM.RAW.SEJM_STAGE
  FILE_FORMAT = SEJM.RAW.JSON_ARRAY;

CREATE TABLE IF NOT EXISTS SEJM.RAW.VOTINGS (
  DOC        VARIANT,
  SRC_FILE   STRING,
  LOADED_AT  TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SEJM.RAW.MPS (
  DOC        VARIANT,
  LOADED_AT  TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SEJM.RAW.CLUBS (
  DOC        VARIANT,
  LOADED_AT  TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
