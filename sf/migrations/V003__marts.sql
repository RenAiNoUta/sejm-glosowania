-- Rdzeń modelu jako Dynamic Tables: Snowflake sam je odświeża, gdy
-- zmienią się dane źródłowe (najpóźniej po TARGET_LAG).
-- Pozostałe marty z sql/20_marts.sql (frekwencja, lojalność, zgodność
-- klubów…) przenieś sam – to dobre ćwiczenie.

CREATE OR REPLACE DYNAMIC TABLE SEJM.MARTS.INT_BILL_VOTINGS
  TARGET_LAG = '1 day'
  WAREHOUSE = SEJM_WH
AS
SELECT
  *,
  IFF(CATEGORY IN ('immunitet', 'wotum'), 'glos-' || VOTING_ID,
      COALESCE('druk-' || PRINT_NO, 'tytul-' || MD5(BILL_TITLE))) AS BILL_ID
FROM SEJM.STAGING.STG_VOTINGS
WHERE CATEGORY IN ('calosc', 'odrzucenie', 'weto', 'immunitet', 'wotum');

CREATE OR REPLACE DYNAMIC TABLE SEJM.MARTS.FCT_BILL_STANCE
  TARGET_LAG = '1 day'
  WAREHOUSE = SEJM_WH
AS
WITH votes AS (
  SELECT b.BILL_ID, b.VOTED_AT, b.VOTING_NUMBER, b.POLARITY, v.MP_ID, v.CLUB, v.VOTE
  FROM SEJM.MARTS.INT_BILL_VOTINGS b
  JOIN SEJM.STAGING.STG_VOTES v ON v.VOTING_ID = b.VOTING_ID
  WHERE v.VOTE <> 'VOTE_VALID'
),
eligible AS (
  SELECT BILL_ID, MP_ID, MAX_BY(CLUB, VOTED_AT) AS CLUB
  FROM votes
  GROUP BY BILL_ID, MP_ID
),
last_vote AS (
  SELECT BILL_ID, MP_ID, VOTE, POLARITY
  FROM votes
  WHERE VOTE IN ('YES', 'NO', 'ABSTAIN')
  QUALIFY ROW_NUMBER() OVER (PARTITION BY BILL_ID, MP_ID ORDER BY VOTED_AT DESC, VOTING_NUMBER DESC) = 1
)
SELECT
  e.BILL_ID, e.MP_ID, e.CLUB,
  CASE l.VOTE WHEN 'YES' THEN l.POLARITY WHEN 'NO' THEN -l.POLARITY WHEN 'ABSTAIN' THEN 0 END AS STANCE
FROM eligible e
LEFT JOIN last_vote l ON l.BILL_ID = e.BILL_ID AND l.MP_ID = e.MP_ID;

CREATE OR REPLACE DYNAMIC TABLE SEJM.MARTS.MART_CLUB_BILL
  TARGET_LAG = '1 day'
  WAREHOUSE = SEJM_WH
AS
SELECT
  BILL_ID, CLUB,
  COUNT_IF(STANCE = 1)      AS N_SUPPORT,
  COUNT_IF(STANCE = -1)     AS N_OPPOSE,
  COUNT_IF(STANCE = 0)      AS N_ABSTAIN,
  COUNT_IF(STANCE IS NULL)  AS N_ABSENT
FROM SEJM.MARTS.FCT_BILL_STANCE
GROUP BY BILL_ID, CLUB;
